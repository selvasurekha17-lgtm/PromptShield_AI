class PromptStrategyResult(BaseModel):
    """Output generated by a single prompt engineering strategy."""
    strategy_id: str
    strategy_name: str
    system_prompt: str
    user_prompt: str
    raw_response: str
    is_structured: bool
    parsed_json: Optional[Dict[str, Any]] = None
    injection_resisted: bool
    evidence_grounded: bool
    uncertainty_disclosed: bool
    execution_source: str
    latency_ms: int = 0


class PromptLabComparison(BaseModel):
    """Comprehensive comparative evaluation of two prompt strategies."""
    message: str
    source: str
    language: str
    strategy_1: PromptStrategyResult
    strategy_2: PromptStrategyResult
    scorecard: Dict[str, Any]
    timestamp: str = Field(default_factory=lambda: datetime.now().strftime("%Y-%m-%d %H:%M:%S"))


