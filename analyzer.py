# ==============================================================================
# Pydantic Data Models: Primary Threat Assessment
# ==============================================================================

class RiskLevel(str, Enum):
    """Four-tier categorical risk rating for incoming messages."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class RedFlag(BaseModel):
    """Specific suspicious phrase and its associated security reasoning."""
    phrase: str = Field(description="Exact phrase quoted verbatim from the original message")
    reason: str = Field(description="Why this phrase is suspicious or poses a threat")
    category: str = Field(
        default="General Suspicion",
        description="Scam taxonomy category (e.g., Urgency, Credential Theft, Impersonation)"
    )
    severity: str = Field(
        default="MEDIUM",
        description="Severity level of this particular indicator: LOW, MEDIUM, HIGH, CRITICAL"
    )


class RiskAnalysisResult(BaseModel):
    """Structured security assessment returned by PromptShield AI."""
    risk_level: RiskLevel = Field(description="Overall categorical risk rating")
    risk_score: int = Field(
        ge=0, le=100,
        description="Heuristic risk score from 0 (harmless) to 100 (severe threat)"
    )
    message_type: str = Field(
        description="Categorization of the message (e.g. Bank Phishing, Delivery Scam, Legitimate Notification)"
    )
    summary: str = Field(
        description="High-level, plain-language explanation of the security assessment"
    )
    red_flags: List[RedFlag] = Field(
        default_factory=list,
        description="List of detected red flag phrases with specific justifications"
    )
    evidence: List[str] = Field(
        default_factory=list,
        description="Observable facts and indicators present within the message"
    )
    recommended_actions: List[str] = Field(
        default_factory=list,
        description="Actionable, prioritized safety recommendations for the recipient"
    )
    safe_reply: str = Field(
        description="A safe, neutral response or advice on whether replying is safe"
    )
    confidence: str = Field(
        default="Medium",
        description="Confidence level in the assessment (Low, Medium, High)"
    )
    uncertainty_notes: str = Field(
        default="",
        description="Transparent disclosure of missing context, assumptions, or limitations"
    )
    analysis_source: str = Field(
        default="Gemini AI",
        description="Origin of the analysis (e.g. Gemini AI or Local Heuristic Engine)"
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        description="Timestamp of when the analysis was performed"
    )


