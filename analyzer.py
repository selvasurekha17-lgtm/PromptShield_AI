# ==============================================================================
# Bounded Retries Helper for Transient API Exceptions
# ==============================================================================

def is_transient_api_error(exception: BaseException) -> bool:
    """Determine whether an API exception qualifies for bounded retry."""
    err_str = str(exception).lower()
    return any(code in err_str for code in ["503", "429", "rate limit", "temporarily unavailable", "timeout", "timed out", "deadline", "resource exhausted"])


@retry(
    stop=stop_after_attempt(3),
    wait=wait_exponential(multiplier=1, min=1, max=4),
    retry=retry_if_exception(is_transient_api_error),
    reraise=True,
)
def _call_gemini_with_retries(client: Any, model: str, contents: str, config: Any) -> Any:
    """Execute Gemini API generation with bounded retries on 503/429 transient errors."""
    return client.models.generate_content(
        model=model,
        contents=contents,
        config=config,
    )


# ==============================================================================
# Gemini AI Analysis Service (Primary Pipeline)
# ==============================================================================

def analyze_message_with_gemini(
    message: str,
    source: str = "Unknown",
    language: str = "English",
    force_offline: bool = False
) -> RiskAnalysisResult:
    """Analyze a suspicious message using Google Gemini with structured Pydantic validation."""
    if not message or not message.strip():
        raise ValueError("Please provide a valid message to analyze. Input cannot be empty.")

    cleaned_message = message.strip()

    if force_offline or not is_api_configured():
        return analyze_message_offline(cleaned_message, source=source, language=language)

    client = get_client()
    if client is None:
        fallback_res = analyze_message_offline(cleaned_message, source=source, language=language)
        fallback_res.uncertainty_notes += " (Gemini client uninitialized; fell back to local engine.)"
        return fallback_res

    user_prompt = USER_PROMPT_TEMPLATE.format(
        source=source,
        language=language,
        message=cleaned_message
    )

    try:
        from google.genai import types

        config = types.GenerateContentConfig(
            system_instruction=SYSTEM_PROMPT,
            temperature=0.1,
            response_mime_type="application/json",
            response_schema=RiskAnalysisResult,
        )

        response = _call_gemini_with_retries(
            client=client,
            model=MODEL_NAME,
            contents=user_prompt,
            config=config,
        )

        if not response or not response.text:
            raise ValueError("Gemini returned an empty response.")

        raw_text = response.text.strip()
        if raw_text.startswith("```"):
            raw_text = re.sub(r"^```(?:json)?\s*", "", raw_text)
            raw_text = re.sub(r"\s*```$", "", raw_text)

        parsed_dict = json.loads(raw_text)
        result = RiskAnalysisResult.model_validate(parsed_dict)
        result.analysis_source = f"Gemini AI ({MODEL_NAME})"
        return result

    except Exception as api_err:
        err_msg = str(api_err).lower()
        fallback_result = analyze_message_offline(cleaned_message, source=source, language=language)

        if "timeout" in err_msg or "timed out" in err_msg or "deadline" in err_msg:
            status_desc = "Gemini API request timed out."
        elif "503" in err_msg or "unavailable" in err_msg:
            status_desc = "Gemini service temporarily unavailable (HTTP 503)."
        elif "quota" in err_msg or "429" in err_msg or "rate" in err_msg:
            status_desc = "Gemini API rate limit or quota exceeded."
        elif "getaddrinfo" in err_msg or "connect" in err_msg or "network" in err_msg:
            status_desc = "Network connection failed."
        elif "api_key" in err_msg or "unauthorized" in err_msg or "401" in err_msg or "403" in err_msg:
            status_desc = "Gemini API key authorization error."
        else:
            status_desc = "Gemini API encountered an operational issue."

        fallback_result.uncertainty_notes = (
            f"[NOTICE: {status_desc} Switched automatically to PromptShield Local Heuristic Engine. "
            "Never claim 100% accuracy without corroborating evidence.]"
        )
        return fallback_result



